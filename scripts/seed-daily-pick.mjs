#!/usr/bin/env node
// Seed the curated Daily Pick shelf from scripts/daily-pick-seed.json.
//
//   node scripts/seed-daily-pick.mjs --print-sql   → writes the SQL to stdout
//   node scripts/seed-daily-pick.mjs               → inserts directly
//                                                    (needs NEXT_PUBLIC_SUPABASE_URL
//                                                     + SUPABASE_SERVICE_ROLE_KEY)
//
// Idempotent by content: a row whose payload->>'text' already exists for that
// kind is skipped, so re-running after adding ten more questions inserts only
// the ten. Never truncates — student submissions live in the same table.
//
// Two things this script is deliberately careful about:
//
//  1. curated = true, display_name = 'CareerRai'. This content is ours. Writing
//     it in under an invented student first name is what TRUST-OS rule 1
//     forbids ("no invented testimonials… never invent a student's words"), and
//     it is the same misrepresentation that got iOS 1.0 rejected under 2.3.10.
//
//  2. Section round-robin ordering. The Top Pick queue promotes oldest-first
//     among items that have never held the slot, so inserting all ten QA
//     questions together would give students ten consecutive QA days. Rows are
//     written QA → DILR → VARC → QA → … so the month alternates by itself.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(readFileSync(join(HERE, 'daily-pick-seed.json'), 'utf-8'));

const VOTING_WINDOW_HOURS = 72; // mirrors lib/community-pipeline
const SECTIONS = ['QA', 'DILR', 'VARC'];

/** Interleave by section so consecutive days rotate sections. */
function roundRobin(items) {
  const queues = SECTIONS.map((s) => items.filter((i) => i.section === s));
  const out = [];
  for (let i = 0; out.length < items.length; i++) {
    for (const q of queues) if (q[i]) out.push(q[i]);
  }
  return out;
}

const questions = roundRobin(seed.questions);
const tips = roundRobin(seed.tips);

function rows() {
  const all = [];
  questions.forEach((q) => all.push({
    kind: 'question',
    topic: q.topic,
    payload: {
      text: q.text, section: q.section, options: q.options,
      correct_index: q.correct_index, explanation: q.explanation,
    },
  }));
  tips.forEach((t) => all.push({
    kind: 'tip',
    topic: t.topic,
    payload: { text: t.text, section: t.section },
  }));
  return all;
}

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;

function toSql() {
  const all = rows();
  const values = all.map((r, i) => [
    '(',
    '(select id from public.profiles where role = \'admin\' order by created_at limit 1),',
    `${sq(r.kind)},`,
    `${sq(r.topic)},`,
    `${sq(JSON.stringify(r.payload))}::jsonb,`,
    `'voting',`,
    `'CareerRai',`,
    'true,',
    // Strict ordering: one second apart, so the queue's oldest-first tie-break
    // is deterministic rather than whatever order Postgres returns.
    `now() + make_interval(secs => ${i}),`,
    `now() + interval '${VOTING_WINDOW_HOURS} hours'`,
    ')',
  ].join(' ')).join(',\n  ');

  return `-- Generated by scripts/seed-daily-pick.mjs — do not hand-edit.
-- ${questions.length} curated questions + ${tips.length} curated tips.
insert into public.student_submissions
  (student_id, kind, topic, payload, status, display_name, curated, created_at, voting_ends_at)
select * from (values
  ${values}
) as v(student_id, kind, topic, payload, status, display_name, curated, created_at, voting_ends_at)
where not exists (
  -- Content-keyed idempotency: same kind + same text is already on the shelf.
  select 1 from public.student_submissions e
   where e.kind = v.kind and e.payload->>'text' = v.payload->>'text'
);
`;
}

if (process.argv.includes('--print-sql')) {
  process.stdout.write(toSql());
} else {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error('Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY, or pass --print-sql.');
    process.exit(1);
  }
  const { createClient } = await import('@supabase/supabase-js');
  const admin = createClient(url, key, { auth: { persistSession: false } });

  const { data: adminProfile } = await admin
    .from('profiles').select('id').eq('role', 'admin').order('created_at').limit(1).single();
  if (!adminProfile) { console.error('No admin profile found to own curated rows.'); process.exit(1); }

  const { data: existing } = await admin
    .from('student_submissions').select('kind, payload');
  const seen = new Set((existing ?? []).map((r) => `${r.kind}::${r.payload?.text ?? ''}`));

  const fresh = rows().filter((r) => !seen.has(`${r.kind}::${r.payload.text}`));
  if (fresh.length === 0) { console.log('Nothing new — shelf already has all of it.'); process.exit(0); }

  const base = Date.now();
  const { error } = await admin.from('student_submissions').insert(
    fresh.map((r, i) => ({
      student_id: adminProfile.id,
      kind: r.kind,
      topic: r.topic,
      payload: r.payload,
      status: 'voting',
      display_name: 'CareerRai',
      curated: true,
      created_at: new Date(base + i * 1000).toISOString(),
      voting_ends_at: new Date(base + VOTING_WINDOW_HOURS * 3600_000).toISOString(),
    })),
  );
  if (error) { console.error(error); process.exit(1); }
  console.log(`Inserted ${fresh.length} curated items.`);
}
